package helpers

import (
	"github.com/google/uuid"
	"github.com/onsi/gomega"
	ovnv1 "github.com/openstack-k8s-operators/ovn-operator/api/v1beta1"
	k8s_errors "k8s.io/apimachinery/pkg/api/errors"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/types"
)

// CreateOVSDBRelay creates a new OVSDBRelay instance with the specified name
// and namespace in the Kubernetes cluster. If name is not passed (nil), it will
// be autogenerated.
//
// Example usage:
//
//	ovsdbRelay := th.CreateOVSDBRelay(nil, namespace, spec)
//	DeferCleanup(th.DeleteOVSDBRelay, ovsdbRelay)
func (th *TestHelper) CreateOVSDBRelay(relayName *string, namespace string, spec ovnv1.OVSDBRelaySpec) types.NamespacedName {
	name := "ovsdbrelay-" + uuid.New().String()
	if relayName != nil {
		name = *relayName
	}
	ovsdbRelay := &ovnv1.OVSDBRelay{
		TypeMeta: metav1.TypeMeta{
			APIVersion: "ovn.openstack.org/v1beta1",
			Kind:       "OVSDBRelay",
		},
		ObjectMeta: metav1.ObjectMeta{
			Name:      name,
			Namespace: namespace,
		},
		Spec: spec,
	}

	gomega.Expect(th.K8sClient.Create(th.Ctx, ovsdbRelay)).Should(gomega.Succeed())
	th.Logger.Info("OVSDBRelay created", "OVSDBRelay", name)
	return types.NamespacedName{Namespace: namespace, Name: name}
}

// DeleteOVSDBRelay deletes a OVSDBRelay resource from the Kubernetes cluster.
//
// After the deletion, the function checks again if the OVSDBRelay is
// successfully deleted.
func (th *TestHelper) DeleteOVSDBRelay(name types.NamespacedName) {
	gomega.Eventually(func(g gomega.Gomega) {
		ovsdbRelay := &ovnv1.OVSDBRelay{}
		err := th.K8sClient.Get(th.Ctx, name, ovsdbRelay)
		// if it is already gone that is OK
		if k8s_errors.IsNotFound(err) {
			return
		}
		g.Expect(err).NotTo(gomega.HaveOccurred())

		g.Expect(th.K8sClient.Delete(th.Ctx, ovsdbRelay)).Should(gomega.Succeed())

		err = th.K8sClient.Get(th.Ctx, name, ovsdbRelay)
		g.Expect(k8s_errors.IsNotFound(err)).To(gomega.BeTrue())
	}, th.Timeout, th.Interval).Should(gomega.Succeed())
}

// GetOVSDBRelay retrieves a OVSDBRelay resource.
func (th *TestHelper) GetOVSDBRelay(name types.NamespacedName) *ovnv1.OVSDBRelay {
	instance := &ovnv1.OVSDBRelay{}
	gomega.Eventually(func(g gomega.Gomega) {
		g.Expect(th.K8sClient.Get(th.Ctx, name, instance)).Should(gomega.Succeed())
	}, th.Timeout, th.Interval).Should(gomega.Succeed())
	return instance
}
